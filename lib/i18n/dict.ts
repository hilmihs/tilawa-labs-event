/**
 * Production lands on Arabic: the committee wanted the site, like its social
 * accounts, to lead with Arabic rather than follow the phone's language.
 *
 * This demo deployment lands on English instead, because the people reading it
 * are hiring managers rather than participants. The Arabic build is one tap
 * away in the header, and nothing else about the bilingual handling changes -
 * `dirOf` still flips the document to RTL, and both dictionaries are complete.
 */
export const DEFAULT_LANG: Lang = "en";

export function isLang(v: string | undefined): v is Lang {
  return v === "en" || v === "ar";
}

export function dirOf(lang: Lang): "ltr" | "rtl" {
  return lang === "ar" ? "rtl" : "ltr";
}

