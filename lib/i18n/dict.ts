/**
 * Arabic has no neutral second person: every imperative and every verb aimed at the
 * reader is either masculine or feminine. `ar` above is written in the masculine,
 * which is the only sane default while we do not know who is reading. Once we do —
 * the participant row says `akhwat`, or she has just tapped "الطالبات" on the form —
 * leaving it masculine reads as a form addressed to somebody else.
 *
 * Only the sentences that actually change are listed here. Lines that are impersonal
 * ("يُرجى…", "لا يُسمح…"), first person ("قرأت", "لديّ رمز"), or whose gender marking
 * vanishes without diacritics ("حفظتها", "سجّلت به") are deliberately absent: they are
 * already correct for both readers, and repeating them would be two copies to keep in
 * step. Arrays are the exception — they are replaced whole, because merging them
 * element-by-element would pair up unrelated bullets the day a list grows.
 */
