/**
 * Plain objects merge key by key; anything else (arrays, strings, null) replaces the
 * value below it outright. See the note on `arAkhwat` for why arrays are not merged.
 */
function gabungDalam(dasar: unknown, atas: unknown): unknown {
  if (atas === undefined) return dasar;
  const bisaGabung = (v: unknown) => typeof v === "object" && v !== null && !Array.isArray(v);
  if (!bisaGabung(dasar) || !bisaGabung(atas)) return atas;
  const hasil = { ...(dasar as Record<string, unknown>) };
  for (const [k, v] of Object.entries(atas as Record<string, unknown>)) {
    hasil[k] = gabungDalam(hasil[k], v);
  }
  return hasil;
}

// Merged once at module load: `t()` is called dozens of times per render.
const arAkhwatPenuh = gabungDalam(ar, arAkhwat) as Dict;

export const DICT: Record<Lang, Dict> = { en, ar };

/**
 * `gender` is optional on purpose: the many call sites that cannot know who is
 * reading — the programme landing page, the programme list — keep working unchanged
 * and keep getting the masculine default.
 */
export function t(lang: Lang, gender?: string | null): Dict {
  if (lang === "ar" && gender === "akhwat") return arAkhwatPenuh;
  return DICT[lang] ?? DICT.en;
}
